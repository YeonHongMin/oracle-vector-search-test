-- SYS @ PDB1 — essentials
CREATE USER soe IDENTIFIED BY soe
  DEFAULT TABLESPACE ts_vector TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON ts_vector;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE, CREATE TYPE,
      CREATE SEQUENCE, CREATE SYNONYM, CREATE JOB, CREATE MINING MODEL, CREATE CREDENTIAL TO soe;
GRANT EXECUTE ON SYS.DBMS_VECTOR TO soe;
GRANT SELECT ON SYS.V_$VECTOR_INDEX TO soe;
GRANT SELECT ON SYS.V_$VECTOR_MEMORY_POOL TO soe;
CREATE OR REPLACE DIRECTORY onnx_dir     AS '/backup/poc_models';
CREATE OR REPLACE DIRECTORY poc_data_dir AS '/backup/poc_data';
GRANT READ ON DIRECTORY onnx_dir TO soe;
GRANT READ, WRITE ON DIRECTORY poc_data_dir TO soe;
